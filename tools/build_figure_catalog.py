    # Preserve every original image/PDF asset, even when no plotting code is known.
    assets = []
    for path in sorted(ROOT.glob('*_analysis/data/**/*')):
        if path.is_file() and path.suffix.lower() in {'.pdf', '.png', '.jpg', '.jpeg', '.svg', '.tif', '.tiff', '.gif'}:
            source = path.relative_to(ROOT).as_posix()
            folder = 'assets/' + re.sub(r'[^A-Za-z0-9_-]+', '_', path.stem)
            assets.append(dict(source=source, folder=folder, sha256=digest(path.read_bytes()), status='asset'))
