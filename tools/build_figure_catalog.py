def digest(data):
    return hashlib.sha256(data).hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, indent=2) + '\n').encode()


def call_end(lines, start, name):
    """Find the closing parenthesis, ignoring quoted parentheses and R comments."""
    depth = 0
    quote = None
    seen = False
    for n in range(start, len(lines)):
        escaped = False
        line = lines[n]
        if n == start:
            line = line[line.index('(', line.index(name)):]
        for c in line:
            if escaped:
                escaped = False
                continue
            if quote and c == '\\':
                escaped = True
            elif quote:
                if c == quote:
                    quote = None
            elif c in '\"\'`':
                quote = c
            elif c == '#':
                break
            elif c == '(':
                depth += 1
                seen = True
            elif c == ')':
                depth -= 1
                if seen and depth == 0:
                    return n + 1
    raise ValueError(f'Unclosed {name} at {start + 1}')


def labels_for(output, source):
    name = Path(output).stem
    if source.endswith('boxplots.R') and name in ('3a', '3d', '3e'):
        return ['Extended_03' + name[-1].upper()]
    norm = re.sub(r'(?i)(ext_?fig_?|ex_?fig_?)', 'S', name)
    norm = re.sub(r'(?i)fig_?', 'F', norm)
    norm = re.sub(r'(?<=\d)_(?=[A-Za-z])', '', norm)
    if re.match(r'^\d', norm):
        norm = 'F' + norm
    result = []
    for m in re.finditer(r'(?i)(?:^|_)([FS])(\d+)_?([A-Z])', norm):
        prefix, num, panel = m.groups()
        label = ('Extended_' if prefix.upper() == 'S' else 'Figure_') + f'{int(num):02d}' + panel.upper()
        if label not in result:
            result.append(label)
    # Bulk outputs prefix supplementary figures with lowercase s.
    m = re.match(r'^s(\d+)([a-z])', name)
    if m and not result:
        result = [f'Extended_{int(m[1]):02d}{m[2].upper()}']
    return result


def chart_type(text, source, output):
    if source.endswith('code_Extended5D_pyscenic.py'):
        return 'rank'
    if re.search(r'forestplot\s*\(', text):
        return 'forest'
    if re.search(r'Spatial(?:Feature|Dim)Plot|sc\.pl\.spatial', text):
        return 'spatial'
    if re.search(r'\b(?:DimPlot|FeaturePlot)\s*\(', text):
        return 'embedding'
    if re.search(r'\b(?:pheatmap|Heatmap|heatmap(?:\.2)?)\s*\(', text):
        return 'heatmap'
    if re.search(r'ggsurvplot|survfit\(', text):
        return 'survival'
    if re.search(r'ggviolin|geom_violin|createEntropyViolinplots', text):
        return 'violin'
    if re.search(r'ggboxplot|geom_boxplot|sns\.boxplot|createBoxplots', text):
        return 'box'
    if re.search(r'DotPlot|dotplot\(|ggdotchart|size\s*=\s*(?:neg|p53)|generateRegressionPlot', text):
        return 'dot'
    if re.search(r'barplot|geom_bar|geom_col', text):
        return 'bar'
    if 'geom_smooth' in text and 'geom_point' not in text:
        return 'trend'
    if re.search(r'geom_point|ggscatter|plot\(', text):
        return 'scatter'
    return 'unknown'


def dependencies(path, text):
    """Report script-level literal input candidates, not per-panel dependency claims."""
    found = {}
    data_dir = path.parent.parent / 'data'
    for line in text.splitlines():
        if line.lstrip().startswith('#'):
            continue
        if not re.search(r'load\(|read[._A-Za-z]*\(|source\(|read_h5ad|\.read\(', line):
            continue
        for _, literal in STRING.findall(line):
            if not re.search(r'\.(?:Rda|RData|rds|csv|tsv|txt|xlsx|h5ad|gtf|R)$', literal, re.I):
                continue
            if '{' in literal:
                resolved = None
            elif 'data.path' in line or 'DATA_INPUT' in line:
                resolved = data_dir / literal.lstrip('/')
            elif literal.startswith('../'):
                resolved = path.parent / literal
            elif path.parts[-3] == 'spatial_analysis':
                resolved = path.parent.parent / literal
            else:
                resolved = path.parent / literal
            relative = None
            if resolved is not None:
                relative = resolved.resolve().relative_to(ROOT).as_posix()
            found[literal] = {'literal': literal, 'resolved_candidate': relative,
                              'available': bool(resolved and resolved.is_file()),
                              'scope': 'whole_source_script'}
    return list(found.values())


def discover():
    entries, audit = [], []
    for path in sorted(ROOT.glob('*_analysis/codes/*')):
        if path.suffix not in ('.R', '.py'):
            continue
        source = path.relative_to(ROOT).as_posix()
        text = path.read_text()
        lines = text.splitlines(keepends=True)
        dep = dependencies(path, text)
        previous = 0
        sites = []
        for i, line in enumerate(lines):
            if line.lstrip().startswith('#') or not SAVE.search(line):
                continue
            m = SAVE.search(line)
            name = m[1] or 'spatial'
            end = call_end(lines, i, name)
            call = ''.join(lines[i:end])
            names = [s for _, s in STRING.findall(call) if s.lower().endswith('.pdf') and s != '.pdf']
            if name == 'createBoxplots':
                names = [re.search(r'outfileName\s*=\s*[\"\']([^\"\']+)', call)[1] + '.pdf']
            if path.name == 'boxplots.R' and name == 'ggsave' and not names:
                audit.append({'source': source, 'line': i + 1, 'kind': 'shared_save_helper',
                              'reason': 'createBoxplots() 内的动态保存由每次调用分别覆盖'})
                continue
            if name == 'pdf':
                close = next((j + 1 for j in range(end, len(lines)) if re.search(r'^\s*dev\.off\s*\(', lines[j])), None)
                if close is None:
                    raise ValueError(f'{source}:{i + 1}: no dev.off')
                end = close
            if path.name == 'all_spatial_plots.R':
                names = [f'spatial_features_sample_{n:02d}.pdf' for n in range(1, 15)]
            if path.name == 'run_infercnv.py':
                names = [f'{s}_cnv_score.pdf' for s in ['BW09_D', 'BW11_C', 'BW14_B', 'MGH1174_C', 'MGH1174_D']]
            if not names:
                raise ValueError(f'Unclassified output: {source}:{i + 1}: {call}')
            sites.append(i + 1)
            for index, output in enumerate(names):
                labels = labels_for(output, source)
                notes = []
                if path.name == 'all_spatial_plots.R':
                    source_index = [1, 2, 3, 4] + list(range(7, 17))
                    notes.append(f'批量输出第 {index + 1}/14 个样本；原始 spatial_list 下标 {source_index[index]}。实际文件名为 names(spatial_list)[i] + .pdf，样本名需读取外部数据确定。')
                    notes.append('原脚本首行将该批次关联到 Fig 3D、3I、4I、5G；该注释可能使用旧图号，保留原文而不推断最终归属。')
                if path.name == 'run_infercnv.py':
                    notes.append('每个 slide 单独收录；Scanpy 可能自动添加 spatial 前缀。最终路径受原代码 ScanpyConfig.figdir 设置及库版本影响。')
                if output == 'F4D_enrichment.pdf':
                    notes.append('图号冲突：章节注释为 F5D pathway enrichment，输出文件却为 F4D_enrichment.pdf。保留两者，未擅自更正。')
                    labels.append('Figure_05D')
                if output.startswith('S9C_'):
                    notes.append('图号冲突：输出名是 S9C，但位于 S7C_continue 章节。可同时在 Extended 7C / 9C 下查找，最终论文归属待核对。')
                    labels.append('Extended_07C')
                if output == 'Ext_Fig5D.pdf':
                    notes.append('图号冲突：文件名和输出名为 Extended 5D，代码内部注释为 Extended 7D。')
                    labels.append('Extended_07D')
                context = ''.join(lines[previous:end])
                kind = chart_type(''.join(lines[i:end]), source, output) if name == 'pdf' else 'unknown'
                if kind == 'unknown':
                    kind = chart_type(context, source, output)
                if output == 'Fig1_overview/Ext_Fig1D.pdf':
                    kind = 'box'  # mean.plots is built in the preceding Figure 1F section.
                entries.append(dict(source=source, source_sha256=digest(path.read_bytes()),
                                    start=previous + 1, end=end, output_line=i + 1, output=output,
                                    labels=labels, status='active', type=kind,
                                    notes=notes, inputs=dep,
                                    selector={'iteration': index + 1, 'count': len(names)} if len(names) > 1 else None))
            previous = end
        if not sites:
            audit.append({'source': source, 'line': None, 'kind': 'support_only',
                          'reason': '统计检验脚本，没有发现绘图或图像保存命令'})
    # Interactive plots lacking ggsave/pdf, and explicit placeholders/history.
    extras = [
        ('singlecell_analysis/codes/code_lymphoid_panels.R', 375, 432, 'Figure_6F_left_interactive', ['Figure_06F'], 'interactive', 'box', 'Figure 6F 左侧 PVR 患者均值箱线图；仅写 CSV，没有保存图像。'),
        ('singlecell_analysis/codes/code_lymphoid_panels.R', 375, 461, 'Figure_6F_right_interactive', ['Figure_06F'], 'interactive', 'scatter', 'Figure 6F 右侧 PVR 与细胞周期分数相关性图；仅写 CSV，没有保存图像。'),
        ('bulk_analysis/codes/regressionModel.R', 166, 168, 'Figure_3C_placeholder', ['Figure_03C'], 'missing_code', 'unknown', '原代码仅有 FIG 3C / add code here 注释，无法提供实现或原图。'),
        ('bulk_analysis/codes/regressionModel.R', 185, 202, 's4b_old.pdf', ['Extended_04B'], 'archived', 'dot', '原注释写明该图在修订时被移除。'),
        ('bulk_analysis/codes/entropy.R', 121, 133, 's4c.pdf', ['Extended_04C'], 'archived', 'violin', '全部绘图语句均已注释。'),
        ('bulk_analysis/codes/entropy.R', 155, 183, 'new_entropy.comut4.pdf', ['Extended_05C'], 'archived', 'violin', '该代码全部注释；相邻 Figure 3J 为另一个含正常组织的现行版本。'),
    ]
    for source, start, end, output, labels, status, kind, note in extras:
        path = ROOT / source
        entries.append(dict(source=source, source_sha256=digest(path.read_bytes()),
                            start=start, end=end, output_line=None, output=output, labels=labels,
                            status=status, type=kind, notes=[note], inputs=dependencies(path, path.read_text()), selector=None))
    for entry in entries:
        domain = entry['source'].split('_analysis')[0]
        category = 'main' if any(l.startswith('Figure_') for l in entry['labels']) else 'extended' if entry['labels'] else 'other'
        if entry['status'] in ('archived', 'missing_code'):
            category = 'history_and_missing'
        slug = re.sub(r'[^A-Za-z0-9_-]+', '_', Path(entry['output']).stem).strip('_')
        entry['folder'] = f'{category}/{domain}__{slug}'
    return sorted(entries, key=lambda e: e['folder']), audit


